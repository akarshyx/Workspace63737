def t(user_id: str, key: str, **kwargs) -> str:
    """Return translated string for user_id's language. Falls back to English."""
    lang = get_user_lang(str(user_id))
    lang_strings = STRINGS.get(key, {})
    text = lang_strings.get(lang) or lang_strings.get("en", f"[{key}]")
    if kwargs:
        try:
            text = text.format(**kwargs)
        except (KeyError, IndexError):
            pass
    return text
